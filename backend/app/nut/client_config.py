def detect_local_lan_ip() -> str:
    """Best-effort detection of the host's primary outbound LAN IPv4 address."""
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
            # Non-sending UDP connect to RFC 5737 TEST-NET-1 to resolve outbound interface
            sock.connect(("192.0.2.1", 80))
            ip = sock.getsockname()[0]
            if ip and not ip.startswith("127."):
                return ip
    except OSError:
        pass
    try:
        ip = socket.gethostbyname(socket.gethostname())
        if ip and not ip.startswith("127."):
            return ip
    except OSError:
        pass
    return "127.0.0.1"


def _build_upsmon_conf(
    server_host: str,
    nut_port: int,
    ups_name: str,
    username: str,
    password: str,
    final_delay: int,
    poll_freq: int,
    deadtime: int,
    shutdown_cmd: str,
) -> str:
    host_port = server_host if nut_port == 3493 else f"{server_host}:{nut_port}"
    escaped_shutdown = shutdown_cmd.replace('"', '\\"')
    lines = [
        "# Generated by WEBNUT — Secondary NUT Client",
        f"MONITOR {ups_name}@{host_port} 1 {username} {password} secondary",
        "MINSUPPLIES 1",
        f'SHUTDOWNCMD "{escaped_shutdown}"',
        f"POLLFREQ {poll_freq}",
        f"POLLFREQALERT {poll_freq}",
        "HOSTSYNC 15",
        f"DEADTIME {deadtime}",
        "POWERDOWNFLAG /etc/killpower",
        f"FINALDELAY {final_delay}",
        "NOTIFYFLAG ONLINE SYSLOG+WALL",
        "NOTIFYFLAG ONBATT SYSLOG+WALL",
        "NOTIFYFLAG LOWBATT SYSLOG+WALL",
        "NOTIFYFLAG FSD SYSLOG+WALL",
        "NOTIFYFLAG COMMOK SYSLOG+WALL",
        "NOTIFYFLAG COMMBAD SYSLOG+WALL",
        "NOTIFYFLAG SHUTDOWN SYSLOG+WALL",
    ]
    return "\n".join(lines) + "\n"


def generate_client_config(req: NutClientConfigRequest) -> NutClientConfigResponse:
    """Validate inputs and render platform-specific NUT client configuration & scripts."""
    server_host = _ensure_safe_token(req.server_host, "server_host", allow_spaces=False)
    ups_name = _ensure_ident(req.ups_name, "ups_name")
    username = _ensure_ident(req.username, "username")
    password = _ensure_safe_token(req.password, "password", allow_spaces=False)
    shutdown_cmd = _ensure_safe_value(req.shutdown_cmd or "/sbin/shutdown -h +0", "shutdown_cmd")

    upsmon_content = _build_upsmon_conf(
        server_host=server_host,
        nut_port=req.nut_port,
        ups_name=ups_name,
        username=username,
        password=password,
        final_delay=req.final_delay,
        poll_freq=req.poll_freq,
        deadtime=req.deadtime,
        shutdown_cmd=shutdown_cmd,
    )
    nut_conf_content = "# Generated by WEBNUT\nMODE=netclient\n"

    if req.platform == "linux_debian":
        one_liner = (
            "sudo apt-get update && sudo apt-get install -y nut-client && "
            "sudo tee /etc/nut/nut.conf >/dev/null <<'EOF'\n"
            f"{nut_conf_content}"
            "EOF\n"
            "sudo tee /etc/nut/upsmon.conf >/dev/null <<'EOF'\n"
            f"{upsmon_content}"
            "EOF\n"
            "sudo chown root:nut /etc/nut/nut.conf /etc/nut/upsmon.conf && "
            "sudo chmod 640 /etc/nut/nut.conf /etc/nut/upsmon.conf && "
            "sudo systemctl enable --now nut-monitor"
        )
        return NutClientConfigResponse(
            platform=req.platform,
            title="Debian / Ubuntu / Proxmox VE (nut-client)",
            files=[
                GeneratedConfigFile(path="/etc/nut/nut.conf", content=nut_conf_content),
                GeneratedConfigFile(path="/etc/nut/upsmon.conf", content=upsmon_content),
            ],
            one_liner=one_liner,
            notes=[
                "Compatible with Debian, Ubuntu, Raspberry Pi OS, and Proxmox VE nodes.",
                "After running the setup script, verify connectivity with: upsc "
                f"{ups_name}@{server_host}:{req.nut_port}",
                "Ensure BIOS 'Restore on AC Power Loss' is set to Power Off so WEBNUT's staggered WoL recovery controls boot order.",
            ],
        )

    if req.platform == "linux_rhel":
        one_liner = (
            "sudo dnf install -y nut-client && "
            "sudo tee /etc/ups/nut.conf >/dev/null <<'EOF'\n"
            f"{nut_conf_content}"
            "EOF\n"
            "sudo tee /etc/ups/upsmon.conf >/dev/null <<'EOF'\n"
            f"{upsmon_content}"
            "EOF\n"
            "sudo chown root:nut /etc/ups/nut.conf /etc/ups/upsmon.conf && "
            "sudo chmod 640 /etc/ups/nut.conf /etc/ups/upsmon.conf && "
            "sudo systemctl enable --now nut-monitor"
        )
        return NutClientConfigResponse(
            platform=req.platform,
            title="RHEL / Rocky Linux / AlmaLinux / Fedora",
            files=[
                GeneratedConfigFile(path="/etc/ups/nut.conf", content=nut_conf_content),
                GeneratedConfigFile(path="/etc/ups/upsmon.conf", content=upsmon_content),
            ],
            one_liner=one_liner,
            notes=[
                "RHEL-family distributions store NUT configs under /etc/ups/ instead of /etc/nut/.",
                "Verify service health with: sudo systemctl status nut-monitor",
            ],
        )

    if req.platform == "truenas":
        return NutClientConfigResponse(
            platform=req.platform,
            title="TrueNAS SCALE / TrueNAS CORE (System Settings → Services → UPS)",
            files=[GeneratedConfigFile(path="upsmon.conf (Reference)", content=upsmon_content)],
            gui_fields=[
                GeneratedGuiField(label="UPS Mode", value="Slave"),
                GeneratedGuiField(label="Identifier", value=ups_name),
                GeneratedGuiField(label="Remote Host", value=server_host),
                GeneratedGuiField(label="Remote Port", value=str(req.nut_port)),
                GeneratedGuiField(label="Monitor User", value=username),
                GeneratedGuiField(label="Monitor Password", value=password),
                GeneratedGuiField(label="Shutdown Mode", value="UPS reaches low battery"),
                GeneratedGuiField(label="Shutdown Timer (sec)", value=str(req.final_delay)),
            ],
            notes=[
                "In TrueNAS Web UI, open System Settings → Services → UPS (Edit), apply the values above, and toggle the UPS service ON + Start Automatically.",
                "TrueNAS will appear in the Live Connected NUT Clients list within seconds of starting.",
            ],
        )

    if req.platform == "synology":
        return NutClientConfigResponse(
            platform=req.platform,
            title="Synology DSM (Control Panel → Hardware & Power → UPS)",
            files=[GeneratedConfigFile(path="upsmon.conf (Reference)", content=upsmon_content)],
            gui_fields=[
                GeneratedGuiField(label="Enable UPS support", value="Checked"),
                GeneratedGuiField(label="Network UPS type", value="Synology UPS server"),
                GeneratedGuiField(label="Network UPS server IP", value=server_host),
                GeneratedGuiField(label="Expected UPS Name (DSM default)", value="ups"),
                GeneratedGuiField(label="Expected User / Password (DSM default)", value="monuser / secret"),
            ],
            notes=[
                "Note: Synology DSM's built-in GUI hardcodes UPS name 'ups', user 'monuser', and password 'secret' on port 3493 unless customized via SSH.",
                f"If using Synology DSM without SSH customization, name your UPS 'ups' in ups.conf and set 'monuser' password to 'secret' (or configure upsd.users accordingly).",
            ],
        )

    # windows (WinNUT-Client)
    return NutClientConfigResponse(
        platform=req.platform,
        title="Windows (WinNUT-Client)",
        files=[GeneratedConfigFile(path="upsmon.conf (Reference)", content=upsmon_content)],
        gui_fields=[
            GeneratedGuiField(label="NUT Host", value=server_host),
            GeneratedGuiField(label="NUT Port", value=str(req.nut_port)),
            GeneratedGuiField(label="UPS Name", value=ups_name),
            GeneratedGuiField(label="Login / Username", value=username),
            GeneratedGuiField(label="Password", value=password),
            GeneratedGuiField(label="Shutdown Delay (sec)", value=str(req.final_delay)),
        ],
        notes=[
            "Install WinNUT-Client on Windows and enter the connection values above in Preferences → Connection.",
            "Enable 'Wake on Magic Packet' in Windows NIC Device Manager and disable Fast Startup so WoL works reliably after graceful NUT shutdown.",
        ],
    )
